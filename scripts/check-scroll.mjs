import { chromium } from 'playwright-core'
import path from 'node:path'

const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe', headless: true })
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'zh-CN' })).newPage()
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: '记一笔' }).first().click()
await page.getByLabel('金额').fill('88')
await page.getByRole('button', { name: '保存', exact: true }).click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: '统计' }).click()
await page.waitForTimeout(400)
console.log('stats:', await page.evaluate(() => ({ h: document.documentElement.scrollHeight, inner: window.innerHeight })))
await page.evaluate(() => window.scrollTo(0, 99999))
await page.waitForTimeout(400)
console.log('scrollY:', await page.evaluate(() => window.scrollY))
await page.screenshot({ path: path.resolve('.screenshots', '15-stats-bottom.png') })
await page.getByRole('button', { name: '设置' }).click()
await page.waitForTimeout(300)
console.log('settings:', await page.evaluate(() => ({ h: document.documentElement.scrollHeight, inner: window.innerHeight })))
await page.evaluate(() => window.scrollTo(0, 99999))
await page.waitForTimeout(400)
console.log('settings scrollY:', await page.evaluate(() => window.scrollY))
await page.screenshot({ path: path.resolve('.screenshots', '16-settings-bottom.png') })
await browser.close()
